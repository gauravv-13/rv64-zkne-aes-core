#!/usr/bin/env python3
"""Generate a random Zkne test program and its expected register writes.

The program loads random 64-bit values from a table and runs a random
sequence of aes64es / aes64esm / aes64ks1i / aes64ks2 / xor / ld. Source
registers are often taken from the last few destinations, so forwarding
(EX/MEM, MEM/WB, register-file bypass) and load-use stalls are exercised on
both operands. A few instructions write x0 (must be discarded).

Expected results come from a small Python simulation using the golden
model (scripts/zkne_golden.py). The runner compares the core's register
writes with this list and, separately, with Spike's commit log.

    python3 scripts/gen_random_prog.py <out.S> <seed> <n_instructions>
writes <out.S> and <out>.expect.json (the body's register writes in order).
"""
import json
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import zkne_golden as golden  # noqa: E402

POOL = [f"x{i}" for i in range(2, 29)] + ["x31"]   # x1 = table, x29/x30 = TEST_END
TABLE_WORDS = 64
OPS = [("ld", 14), ("aes64es", 18), ("aes64esm", 18), ("aes64ks1i", 18),
       ("aes64ks2", 18), ("xor", 14)]


def generate(seed, n):
    rng = random.Random(seed)
    table = [rng.getrandbits(64) for _ in range(TABLE_WORDS)]
    regs = {r: 0 for r in POOL}
    recent = []
    body, writes, counts = [], [], {}

    def src():
        if recent and rng.random() < 0.6:
            return rng.choice(recent[-3:])
        return rng.choice(POOL)

    def dst():
        return "x0" if rng.random() < 0.02 else rng.choice(POOL)

    def emit(asm, rd, value):
        body.append(asm)
        if rd != "x0":
            regs[rd] = value
            writes.append([int(rd[1:]), value])
            recent.append(rd)

    # start with every pool register loaded
    for r in POOL:
        k = rng.randrange(TABLE_WORDS)
        emit(f"ld {r}, {8 * k}(x1)", r, table[k])

    names, weights = zip(*OPS)
    for _ in range(n):
        op = rng.choices(names, weights)[0]
        counts[op] = counts.get(op, 0) + 1
        rd, a, b = dst(), src(), src()
        if op == "ld":
            k = rng.randrange(TABLE_WORDS)
            rd = rd if rd != "x0" else rng.choice(POOL)
            emit(f"ld {rd}, {8 * k}(x1)", rd, table[k])
        elif op == "aes64ks1i":
            rnum = rng.randrange(11)
            emit(f"aes64ks1i {rd}, {a}, {rnum}", rd, golden.aes64ks1i(regs[a], rnum))
        elif op == "xor":
            emit(f"xor {rd}, {a}, {b}", rd, regs[a] ^ regs[b])
        else:
            emit(f"{op} {rd}, {a}, {b}", rd, golden.OPS[op](regs[a], regs[b], 0))

    src_text = (
        "// GENERATED by scripts/gen_random_prog.py (seed %d, %d instructions).\n"
        "#include \"test.h\"\n"
        "        .section .text.init\n"
        "        .globl _start\n"
        "_start:\n"
        "        la    x1, table\n" % (seed, n)
        + "".join(f"        {line}\n" for line in body)
        + "        TEST_END\n\n        .data\ntable:\n"
        + "".join(f"        .dword 0x{v:016x}\n" for v in table)
    )
    return src_text, writes, counts


if __name__ == "__main__":
    out, seed, n = pathlib.Path(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
    text, writes, counts = generate(seed, n)
    out.write_text(text)
    out.with_suffix(".expect.json").write_text(json.dumps({"writes": writes, "counts": counts}))
    print(f"{out}: {n} instructions, {counts}")
