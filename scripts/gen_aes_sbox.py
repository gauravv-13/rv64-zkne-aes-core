#!/usr/bin/env python3
"""Generate rtl/aes_sbox.v: the AES forward S-box as a case statement.

The table is computed from its definition in FIPS-197 section 5.1.1
(multiplicative inverse in GF(2^8) mod x^8+x^4+x^3+x+1, then the affine
transformation with constant 0x63), not copied from anywhere.

    python3 scripts/gen_aes_sbox.py > rtl/aes_sbox.v
"""


def gf_mul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        a = ((a << 1) ^ (0x11B if a & 0x80 else 0)) & 0x1FF
        b >>= 1
    return p & 0xFF


def gf_inv(a):
    if a == 0:
        return 0                         # FIPS-197: 0 maps to 0
    return next(b for b in range(1, 256) if gf_mul(a, b) == 1)


def sbox(x):
    b = gf_inv(x)
    rotl = lambda v, n: ((v << n) | (v >> (8 - n))) & 0xFF
    return b ^ rotl(b, 1) ^ rotl(b, 2) ^ rotl(b, 3) ^ rotl(b, 4) ^ 0x63


SBOX = [sbox(x) for x in range(256)]
# Spot checks against FIPS-197 Figure 7.
assert SBOX[0x00] == 0x63 and SBOX[0x53] == 0xED and SBOX[0xFF] == 0x16

if __name__ == "__main__":
    print("""`timescale 1ns/1ps

// ---------------------------------------------------------------------------
// aes_sbox - AES forward S-box (FIPS-197 section 5.1.1), combinational.
//
// GENERATED by scripts/gen_aes_sbox.py (computed from the GF(2^8) inverse
// and affine transform). Do not edit by hand.
//
// A plain case statement: no memory and no initial block, so it
// synthesizes to logic and every net can be probed. This is the single
// module to replace with a masked S-box.
// ---------------------------------------------------------------------------
module aes_sbox (
    input      [7:0] in,
    output reg [7:0] out
);

always @(*) begin
    case (in)""")
    for row in range(0, 256, 4):
        print("       " + "".join(f" 8'h{x:02x}: out = 8'h{SBOX[x]:02x};"
                                for x in range(row, row + 4)))
    print("""    endcase
end

endmodule""")
